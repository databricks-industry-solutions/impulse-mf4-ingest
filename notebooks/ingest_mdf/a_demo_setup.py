# MAGIC  
# MAGIC * Creates or resets Unity Catalog objects (catalog, schema, volumes) and a minimal `status` table
# MAGIC * **Demo mode** (`use_demo_data=True`): optional full schema reset and OBD zip → MDF4 staging
# MAGIC * **Live mode** (`use_demo_data=False`): never drops schema/tables; only `CREATE IF NOT EXISTS`; no demo import
